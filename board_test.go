package main

import (
	"strings"
	"testing"
	"time"
)

func boardFixture() []Task {
	due := time.Date(2026, 12, 1, 0, 0, 0, 0, time.UTC)
	overdue := time.Date(2026, 1, 5, 0, 0, 0, 0, time.UTC)
	completed := time.Date(2026, 11, 1, 0, 0, 0, 0, time.UTC)
	return []Task{
		{ID: 1, Title: "Write the report", Description: "Quarterly numbers",
			Project: "work", Priority: PriorityHigh, Status: StatusTodo, Tags: []string{"docs"},
			CreatedAt: time.Now(), DueDate: &due},
		{ID: 2, Title: "Fix login", Project: "work", Priority: PriorityCritical,
			Status: StatusInProgress, CreatedAt: time.Now()},
		{ID: 3, Title: "Blocked on review", Project: "work", Priority: PriorityMedium,
			Status: StatusBlocked, CreatedAt: time.Now()},
		{ID: 4, Title: "Ship v1", Project: "work", Priority: PriorityLow,
			Status: StatusDone, CreatedAt: time.Now(), CompletedAt: &completed},
		{ID: 5, Title: "Renew passport", Project: "home", Priority: PriorityHigh,
			Status: StatusTodo, CreatedAt: time.Now(), DueDate: &overdue},
	}
}

func TestBuildBoardGroupsEveryStatus(t *testing.T) {
	columns := buildBoard(boardFixture())
	if len(columns) != 4 {
		t.Fatalf("expected 4 columns, got %d", len(columns))
	}

	counts := map[string]int{}
	for _, column := range columns {
		counts[column.Key] = column.Count
	}
	want := map[string]int{"todo": 2, "progress": 1, "blocked": 1, "done": 1}
	for key, count := range want {
		if counts[key] != count {
			t.Errorf("column %s has %d cards, want %d", key, counts[key], count)
		}
	}
}

func TestBuildBoardOrdersByPriorityThenDueDate(t *testing.T) {
	columns := buildBoard(boardFixture())
	todo := columns[0]

	// Critical before high, and within high the overdue task first.
	if todo.Cards[0].Priority != string(PriorityHigh) || todo.Cards[0].ID != 5 {
		t.Errorf("first todo card = #%d %s, want the overdue high task #5",
			todo.Cards[0].ID, todo.Cards[0].Priority)
	}
	if todo.Cards[1].ID != 1 {
		t.Errorf("second todo card = #%d, want #1", todo.Cards[1].ID)
	}
}

func TestBuildBoardMarksOverdueButNotCompleted(t *testing.T) {
	columns := buildBoard(boardFixture())
	overdueSeen := false
	for _, column := range columns {
		for _, card := range column.Cards {
			if card.ID == 5 {
				overdueSeen = card.Overdue
			}
			if card.ID == 4 && card.Overdue {
				t.Error("a done task with a past due date must not be marked overdue")
			}
		}
	}
	if !overdueSeen {
		t.Error("expected task #5 to be marked overdue")
	}
}

func TestBuildBoardPutsUnknownStatusInTodo(t *testing.T) {
	columns := buildBoard([]Task{{ID: 1, Title: "odd", Status: Status("nonsense")}})
	if columns[0].Count != 1 {
		t.Errorf("unknown status should land in todo, got %d cards there", columns[0].Count)
	}
}

func TestRenderBoardIsSelfContainedAndEscaped(t *testing.T) {
	tasks := []Task{{
		ID:        1,
		Title:     `<script>alert("x")</script>`,
		Project:   `work & "play"`,
		Priority:  PriorityHigh,
		Status:    StatusTodo,
		Tags:      []string{`<b>`},
		CreatedAt: time.Now(),
	}}

	out, err := renderBoard(tasks)
	if err != nil {
		t.Fatal(err)
	}

	for _, want := range []string{
		"<!DOCTYPE html>",
		"<style>",
		"1 task across 1 project",
		"Generated by go-task-cli",
		"&lt;script&gt;alert(&#34;x&#34;)&lt;/script&gt;",
		"work &amp; &#34;play&#34;",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("board is missing %q", want)
		}
	}
	if strings.Contains(out, "<script") {
		t.Error("board contains a script tag")
	}
	if strings.Contains(out, "<b>") {
		t.Error("tag was not escaped")
	}
	if strings.Contains(out, "<link") || strings.Contains(out, `src="http`) {
		t.Error("board loads an external resource")
	}
}

func TestRenderBoardShowsEmptyColumns(t *testing.T) {
	out, err := renderBoard(nil)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Count(out, "Nothing here.") != 4 {
		t.Errorf("expected all four columns to say they are empty")
	}
	if !strings.Contains(out, "0 tasks across 0 projects") {
		t.Error("missing the empty summary")
	}
}

func TestBoardCommandWritesHTML(t *testing.T) {
	withStore(t)
	store := loadStore()
	store.Tasks = boardFixture()
	if err := saveStore(store); err != nil {
		t.Fatal(err)
	}

	out := runCmd(t, "board")
	if !strings.HasPrefix(out, "<!DOCTYPE html>") {
		t.Errorf("unexpected output: %.60q", out)
	}
	if !strings.Contains(out, "Write the report") {
		t.Error("board is missing a task title")
	}
}

